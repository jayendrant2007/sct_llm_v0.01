import os
import cv2
import torch
import requests
import time
from PIL import Image
from io import BytesIO
from transformers import AutoModelForCausalLM, AutoTokenizer, AutoConfig

class VLMSecurityPipeline:
    def __init__(self, model_id="vikhyatk/moondream2", revision="2024-04-02"):
        """Initialize the Vision-Language Model and push to GPU if available."""
        print(f"Loading VLM ({model_id}) into memory...")
        self.device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

        # Load tokenizer first
        self.tokenizer = AutoTokenizer.from_pretrained(model_id, revision=revision)

        # Load configuration
        config = AutoConfig.from_pretrained(model_id, trust_remote_code=True, revision=revision)

        # Patch the missing pad_token_id attribute in the main config
        pad_id = self.tokenizer.pad_token_id if self.tokenizer.pad_token_id is not None else 0
        if not hasattr(config, 'pad_token_id'):
            config.pad_token_id = pad_id

        # Patch the nested text model configuration (phi_config) as well
        if hasattr(config, 'phi_config'):
            if isinstance(config.phi_config, dict):
                if 'pad_token_id' not in config.phi_config:
                    config.phi_config['pad_token_id'] = pad_id
            else:
                if not hasattr(config.phi_config, 'pad_token_id'):
                    config.phi_config.pad_token_id = pad_id

        # Fix the rope_scaling KeyError: 'type' issue
        # If rope_scaling is defined as an object or has been parsed incorrectly, force convert it
        for cfg in [config, getattr(config, 'phi_config', None)]:
            if cfg is not None:
                # If it's a dictionary container in phi_config
                if isinstance(cfg, dict):
                    if 'rope_scaling' in cfg and cfg['rope_scaling'] is not None:
                        rs = cfg['rope_scaling']
                        if not isinstance(rs, dict):
                            # Convert class objects to a dict with 'type'
                            rope_type = getattr(rs, 'type', getattr(rs, 'rope_type', None))
                            rope_factor = getattr(rs, 'factor', 1.0)
                            cfg['rope_scaling'] = {"type": rope_type, "factor": rope_factor}
                else:
                    if hasattr(cfg, 'rope_scaling') and cfg.rope_scaling is not None:
                        rs = cfg.rope_scaling
                        if not isinstance(rs, dict):
                            rope_type = getattr(rs, 'type', getattr(rs, 'rope_type', None))
                            rope_factor = getattr(rs, 'factor', 1.0)
                            cfg.rope_scaling = {"type": rope_type, "factor": rope_factor}

        # Load model using the fully patched configurations
        self.model = AutoModelForCausalLM.from_pretrained(
            model_id,
            config=config,
            trust_remote_code=True,
            revision=revision,
            torch_dtype=torch.float16 if torch.cuda.is_available() else torch.float32
        ).to(self.device)

        self.model.eval()
        print(f"Model successfully loaded on {self.device}.")

    def trigger_alert(self, webhook_url: str, message: str):
        """Dispatches an alert payload to a webhook (e.g., Slack, Discord, custom API)."""
        payload = {"text": f"🚨 **VLM Alert Triggered:** {message}"}
        if "YOUR/WEBHOOK/URL" in webhook_url:
            print(f"[Mock Alert] Webhook is a placeholder. Would send: {payload}")
            return
        try:
            response = requests.post(webhook_url, json=payload)
            response.raise_for_status()
            print("Alert dispatched successfully.")
        except requests.exceptions.RequestException as e:
            print(f"Failed to dispatch alert: {e}")

    def analyze_single_image(self, pil_img: Image.Image, prompt: str):
        """Helper to run prediction on a single PIL Image."""
        image_embeds = self.model.encode_image(pil_img)
        response = self.model.answer_question(image_embeds, prompt, self.tokenizer)
        return response

    def run_stream_analytics(self, rtsp_url: str, prompt: str, webhook_url: str, analyze_every_n_seconds: int = 5):
        """Connects to RTSP, samples frames, and queries the VLM."""
        cap = cv2.VideoCapture(rtsp_url)

        if not cap.isOpened():
            print(f"Could not connect to RTSP stream: '{rtsp_url}'")
            print("Switching to fallback demo mode using a sample image...")
            # Load a mock image from web for demonstration
            demo_url = "https://images.unsplash.com/photo-1581091226825-a6a2a5aee158" # Construction worker
            try:
                res = requests.get(demo_url)
                img = Image.open(BytesIO(res.content))
                print("Loaded sample image from Unsplash. Running model analysis...")
                response = self.analyze_single_image(img, prompt)
                print(f"VLM Response: {response}")
                if "yes" in response.lower():
                    self.trigger_alert(webhook_url, f"Condition met for prompt: '{prompt}'. VLM detail: {response}")
            except Exception as e:
                print(f"Failed to load demo image: {e}")
            return

        fps = cap.get(cv2.CAP_PROP_FPS)
        if fps <= 0:
            fps = 30.0 # Fallback if RTSP doesn't report FPS

        frame_interval = int(fps * analyze_every_n_seconds)
        frame_count = 0

        print(f"Starting analytics stream. Analyzing 1 frame every {analyze_every_n_seconds} seconds.")

        try:
            while True:
                ret, frame = cap.read()
                if not ret:
                    print("Stream disconnected. Attempting to reconnect...")
                    time.sleep(5)
                    cap = cv2.VideoCapture(rtsp_url)
                    continue

                # Only process frames at the specified interval
                if frame_count % frame_interval == 0:
                    rgb_frame = cv2.cvtColor(frame, cv2.COLOR_BGR2RGB)
                    pil_img = Image.fromarray(rgb_frame)

                    response = self.analyze_single_image(pil_img, prompt)
                    print(f"[{time.strftime('%H:%M:%S')}] VLM Response: {response}")

                    if "yes" in response.lower():
                        self.trigger_alert(webhook_url, f"Condition met for prompt: '{prompt}'. VLM detail: {response}")

                frame_count += 1

        except KeyboardInterrupt:
            print("\nTerminating VLM pipeline...")
        finally:
            cap.release()

if __name__ == "__main__":
    # Configuration
    RTSP_STREAM = os.environ.get("SCT_RTSP_URL")
    if not RTSP_STREAM:
        raise RuntimeError("Set SCT_RTSP_URL to your RTSP stream URL before running.")
    WEBHOOK = os.environ.get("SCT_ALERT_WEBHOOK_URL", "YOUR/WEBHOOK/URL")

    SECURITY_PROMPT = "Is there a person not wearing a high-visibility vest or safety helmet? Answer strictly with 'Yes' or 'No', followed by a brief explanation."

    pipeline = VLMSecurityPipeline()
    pipeline.run_stream_analytics(
        rtsp_url=RTSP_STREAM,
        prompt=SECURITY_PROMPT,
        webhook_url=WEBHOOK,
        analyze_every_n_seconds=3
    )

